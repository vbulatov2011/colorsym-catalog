/*
  affine_classes.mjs - classes of subgroups under the AFFINE NORMALIZER of G.

  The catalogue names one entry per conjugacy class of subgroups of G (#k
  tells them apart).  The classical counts of colour groups - 46 two-colour,
  23 three-colour, 96 four-colour ... wallpaper groups - count fewer, because
  they identify H and H' when an affine map n with nGn^-1 = G carries H onto
  H'.  Such an n is a symmetry of the uncolored group that need not belong to
  it: it may swap G's two families of mirrors, move G's origin to another
  rotation centre of the same kind, or (for a skew lattice) shear the lattice.
  By Bieberbach these maps induce every automorphism of G, so the classes are
  also the orbits of Aut(G) on the subgroups.

  How.  SymmHub's subgroupKey() states a subgroup H exactly in G's canonical
  frame (lattice basis t1, t2 of T(G), an origin): its translation lattice
  T(H) as a Hermite basis, and per linear part M (an integer matrix) the
  offset v of x -> Mx + v, modulo T(H).  An affine map n: x -> Ax + t, A in
  GL(2,Z) and t rational in that frame, acts on that data exactly:

        T(H)  ->  A T(H)
        (M, v) -> (A M A^-1,  A v + t - A M A^-1 t)

  1. the normalizer: every (A, t) with entries of A in -2..2, det A = +-1,
     t on a 1/12 grid of the cell, that carries G's own key to itself.  That
     finite set generates enough of N(G): its continuous part (translations
     along the mirrors of **, *x, xx, every translation of o) fixes each
     subgroup, and the discrete part is generated by small maps.  The check
     is the classical totals (1..6 colours: 17 46 23 96 14 66), which the
     catalogue reproduces;
  2. every conjugate of every entry (the stabilizers of its cosets) has a
     key; each normalizer map carries a key to another key of the list, and
     the entries those keys belong to are merged (union-find).

  export affineClasses({ group, frame, subgroups })
    subgroups: manifest entries ({ name, index, cosets })
    return { classOf: Map name -> least name of its class (by index, then
             name), normalizerSize: number of maps found }

  CLI: node tools/affine_classes.mjs   - adds the fields to every manifest in
  data/ (affineClass per entry, affineCountPerIndex per manifest).  Words and
  coset numbering are not touched.  make_manifest.mjs calls the same code.
*/

import { SYMMHUB_URL as SYMMHUB } from './catalog_paths.mjs';
const { subgroupKey, subgroupClassKey, hermite } =
  await import(SYMMHUB + '/lib/grouplib/SubgroupKey.js');

// ---- exact rationals ---------------------------------------------------------

const gcd = (a, b) => { a = Math.abs(a); b = Math.abs(b); while(b) [a, b] = [b, a % b]; return a; };
function Q(n, d = 1){ if(d < 0){ n = -n; d = -d; } const g = gcd(n, d) || 1; return [n / g, d / g]; }
const qadd = (a, b) => Q(a[0] * b[1] + b[0] * a[1], a[1] * b[1]);
const qsub = (a, b) => Q(a[0] * b[1] - b[0] * a[1], a[1] * b[1]);
const qmulI = (a, k) => Q(a[0] * k, a[1]);
const qfloor = a => Math.floor(a[0] / a[1]);
const qstr = a => a[1] === 1 ? String(a[0]) : a[0] + '/' + a[1];
const qparse = s => { const [p, q] = s.split('/'); return Q(Number(p), q === undefined ? 1 : Number(q)); };

// ---- 2x2 integer matrices, row major [m00, m01, m10, m11] --------------------

const mmul = (a, b) => [a[0] * b[0] + a[1] * b[2], a[0] * b[1] + a[1] * b[3],
                        a[2] * b[0] + a[3] * b[2], a[2] * b[1] + a[3] * b[3]];
const det = a => a[0] * a[3] - a[1] * a[2];
const minv = a => { const d = det(a); return [a[3] * d, -a[1] * d, -a[2] * d, a[0] * d]; }; // det +-1
const mvecI = (a, v) => [a[0] * v[0] + a[1] * v[1], a[2] * v[0] + a[3] * v[1]];
const mvecQ = (a, v) => [qadd(qmulI(v[0], a[0]), qmulI(v[1], a[1])),
                         qadd(qmulI(v[0], a[2]), qmulI(v[1], a[3]))];

// ---- a key as data, and back to the canonical string ---------------------------

function parseKey(k){
  return {
    n: k.index,
    hnf: k.hnf,
    elems: k.elements.map(e => ({ m: e.matrix.slice(), v: e.offset.split(',').map(qparse) })),
  };
}

function keyString(n, hnf, elems){
  const reduce = ([x, y]) => {
    const i = qfloor(Q(x[0], x[1] * hnf.a));
    x = qsub(x, Q(i * hnf.a)); y = qsub(y, Q(i * hnf.b));
    const j = qfloor(Q(y[0], y[1] * hnf.d));
    y = qsub(y, Q(j * hnf.d));
    return [x, y];
  };
  const list = elems.map(e => ({ matrix: e.m, offset: reduce(e.v).map(qstr).join(',') }));
  list.sort((p, q) => {
    for(let i = 0; i < 4; i++) if(p.matrix[i] !== q.matrix[i]) return p.matrix[i] - q.matrix[i];
    return p.offset < q.offset ? -1 : p.offset > q.offset ? 1 : 0;
  });
  return `k1|n=${n}|L=${hnf.a},${hnf.b},${hnf.d}|P=` +
    list.map(e => e.matrix.join(',') + ':' + e.offset).join(';');
}

/** the key of n H n^-1, n = (A, t) */
function conjugateKey(h, A, t){
  const Ai = minv(A);
  const hnf = hermite([mvecI(A, [h.hnf.a, h.hnf.b]), mvecI(A, [0, h.hnf.d])]);
  const elems = h.elems.map(({ m, v }) => {
    const m2 = mmul(mmul(A, m), Ai);
    const Av = mvecQ(A, v), Mt = mvecQ(m2, t);
    return { m: m2, v: [qsub(qadd(Av[0], t[0]), Mt[0]), qsub(qadd(Av[1], t[1]), Mt[1])] };
  });
  return keyString(h.n, hnf, elems);
}

// ---- the normalizer --------------------------------------------------------

function normalizer(gKey){
  const g = parseKey(gKey);
  const target = keyString(g.n, g.hnf, g.elems);
  const maps = [];
  const R = [-2, -1, 0, 1, 2];
  const DEN = 12;
  for(const a of R) for(const b of R) for(const c of R) for(const d of R){
    const A = [a, b, c, d];
    if(Math.abs(det(A)) !== 1) continue;
    for(let i = 0; i < DEN; i++) for(let j = 0; j < DEN; j++){
      const t = [Q(i, DEN), Q(j, DEN)];
      if(conjugateKey(g, A, t) === target) maps.push({ A, t });
    }
  }
  return maps;
}

// ---- the classes -------------------------------------------------------------

export function affineClasses({ group, frame, subgroups }){
  const gKey = subgroupKey({ group, frame, cosets: group.transforms.map(() => [0]) });
  const maps = normalizer(gKey);

  // every conjugate's key -> its entry
  const owner = new Map();
  const conj = new Map();
  for(const s of subgroups){
    const ck = subgroupClassKey({ group, frame, cosets: s.cosets });
    const list = [...ck.keys.values()].map(parseKey);
    conj.set(s.name, list);
    for(const k of ck.keys.values()) owner.set(k.key, s.name);
  }

  const parent = new Map(subgroups.map(s => [s.name, s.name]));
  const find = x => { while(parent.get(x) !== x) x = parent.get(x); return x; };
  for(const s of subgroups){
    const h = conj.get(s.name)[0];
    for(const { A, t } of maps){
      const k = conjugateKey(h, A, t);
      const o = owner.get(k);
      if(o === undefined)
        throw new Error(`affineClasses: ${s.name} maps to a key outside the list: ${k}`);
      const [p, q] = [find(s.name), find(o)];
      if(p !== q) parent.set(p, q);
    }
  }

  const order = new Map(subgroups.map(s => [s.name, [s.index, s.name]]));
  const least = new Map();
  for(const s of subgroups){
    const r = find(s.name);
    const cur = least.get(r);
    const [i, n] = order.get(s.name);
    if(!cur || i < order.get(cur)[0] || (i === order.get(cur)[0] && n < cur)) least.set(r, s.name);
  }
  const classOf = new Map(subgroups.map(s => [s.name, least.get(find(s.name))]));
  return { classOf, normalizerSize: maps.length };
}

/** affineCountPerIndex: number of classes per index, as countPerIndex */
export function affineCounts(subgroups, classOf, maxIndex){
  const out = [];
  for(let n = 1; n <= maxIndex; n++)
    out.push(new Set(subgroups.filter(s => s.index === n).map(s => classOf.get(s.name))).size);
  return out;
}

// ---- CLI: patch the manifests in data/ -------------------------------------

import { fileURLToPath } from 'node:url';
if(process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]){
  const { readFileSync, writeFileSync, readdirSync } = await import('node:fs');
  const { join, dirname } = await import('node:path');
  const { iWallpaperGroup } = await import(SYMMHUB + '/lib/grouplib/WallpaperGroups.js');
  const { Group } = await import(SYMMHUB + '/lib/invlib/invlib.js');
  const { computeFrame } = await import(SYMMHUB + '/lib/grouplib/SubgroupKey.js');

  const { DATA_DIR: DATA } = await import('./catalog_paths.mjs');
  const files = readdirSync(DATA).filter(f => f.endsWith('.json') && f !== 'index.json');
  const totals = [];
  for(const f of files){
    const path = join(DATA, f);
    const m = JSON.parse(readFileSync(path, 'utf8'));
    if(m.format !== 'colorsym-catalog-manifest') continue;
    const g = m.group;
    const group = new Group(iWallpaperGroup({ name: g.name, a: g.geometry.a,
                                              ...(g.domainShape ? { domainShape: g.domainShape } : {}) }));
    const frame = computeFrame(group);
    const { classOf, normalizerSize } = affineClasses({ group, frame, subgroups: m.subgroups });
    const counts = affineCounts(m.subgroups, classOf, m.maxIndex);

    // the same shape as countPerIndex: [{index, count}], non-empty indices only
    const perIndex = counts.map((count, i) => ({ index: i + 1, count })).filter(c => c.count);
    const show = list => list.map(c => c.index + ':' + c.count).join(' ');
    const out = {};
    for(const [k, v] of Object.entries(m)){
      out[k] = k === 'subgroups'
        ? v.map(s => ({ ...s, affineClass: classOf.get(s.name) }))
        : v;
      if(k === 'countPerIndex') out.affineCountPerIndex = perIndex;
    }
    writeFileSync(path, JSON.stringify(out, null, 1));
    console.log(`${f.padEnd(24)} N(G) maps ${String(normalizerSize).padStart(4)}  ` +
                `classes ${show(perIndex)}  (of ${show(m.countPerIndex)})`);
    if(!f.includes('@')) counts.forEach((c, i) => totals[i] = (totals[i] || 0) + c);
  }
  console.log('total classes per index (default manifests):', totals.join(' '));
}
